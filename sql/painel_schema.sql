-- Schema "painel": dados lançados pelo painel (custos, produção hospitalar e SIMAQ).
--
-- Só é necessário se o usuário configurado no painel não puder criar schemas
-- (se puder, o painel cria sozinho). Executar UMA vez, como superusuário (ou
-- dono do banco), no mesmo banco configurado no painel. Como o usuário do
-- painel fica dono do schema, ele mesmo cria as tabelas. O nome do schema é o
-- informado em "Schema dos dados do painel" na configuração do banco.
--
-- Depois disso, ao subir (ou em até 1 minuto, se já estiver rodando), o painel
-- cria as tabelas abaixo e migra as planilhas de dados/ para elas
-- (banco_painel.py). Se o usuário do painel for outro, troque o nome em
-- AUTHORIZATION.

CREATE SCHEMA IF NOT EXISTS painel AUTHORIZATION painel;

-- Tabelas criadas pelo painel (referência):
--
-- painel.custos              (mes, tipo, item, valor)
-- painel.producao_hospitalar (mes, servico, tipo, procedimento, quantidade)
-- painel.simaq               (mes, indicador, tipo, numerador, denominador, resultado, meta)
--
-- Todas com id, atualizado_em e atualizado_por, e UNIQUE (mes, chaves do item).
-- "mes" é DATE no dia 1 do mês de referência.
--
-- Financeiro (relatórios do SIAFE importados em Lançar Dados do Financeiro;
-- cada importação substitui a anterior do mesmo relatório):
--
-- painel.credor                (documento, nome)            CNPJ/CPF só com dígitos
-- painel.importacao_financeiro (tipo, arquivo, referencia, totais...)  'empenhos' ou 'restos'
-- painel.empenho_aberto        (empenho, fonte, credor_documento, valor_a_liquidar, valor_liquidado_a_pagar)
-- painel.resto_pagar           (empenho, processo, fonte, contrato, credor_documento,
--                               ordem_bancaria, data_ob, valor_inscrito, valor_pago, valor_a_pagar)
--
-- Tabelas do sistema, já carregadas na primeira configuração do banco
-- (cada carga registrada em painel.migracao: roda uma vez só):
--
-- painel.tipo_consulta        (nome, ativo, isn_tipo_consulta)
--     nome de cada t_marcacao.isn_tipo_consulta, carregado de
--     tipos_consulta_padrao.csv (nesta pasta). Editável em Cadastros.
--     Sem o arquivo, a carga fica para o próximo início.
-- painel.classificacao_exame  (nome)
-- painel.exame_classificacao  (isn_exame, classificacao_id, dat_classificacao)
--     classificação de cada exame, carregada de classificacao_exames_padrao.csv
--     (nesta pasta; o exame é achado em t_exame pelo nome). Editável em
--     Classificação de Exames. Sem o arquivo, a carga fica para o próximo início.
